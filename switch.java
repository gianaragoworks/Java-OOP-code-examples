class oop {
   public static void main(String[] args){
  int season = 4;
  switch (season) {
    case 1:
        System.out.print("summer");
        break;
    case 2:
        System.out.print("Spring");
        break;
    case 3:
        System.out.print("Autumn");
        break;
    case 4:
        System.out.print("Winter");
        break;
    default:
        System.out.print("No defined season.");
        break;
  }
    }
}


      
    
