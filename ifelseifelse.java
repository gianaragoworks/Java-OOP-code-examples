class oop {
   public static void main(String[] args){
    int grade = 90;

    if(grade >= 90){
        System.out.print("Grade: A");
    }
    else if(grade >= 85){
        System.out.print("Grade: B");
    }
    else if(grade >= 75){
        System.out.print("Grade C");
    }
    else{
        System.out.print("You failed!");
    }
   }
}
